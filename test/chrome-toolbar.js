'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const html = fs.readFileSync(path.join(__dirname, '../public/index.html'), 'utf8');
const css = fs.readFileSync(path.join(__dirname, '../public/style.css'), 'utf8');
const top = html.slice(html.indexOf('chrome-top'), html.indexOf('</header>'));
assert.ok(top.includes('btn-new-tab'), 'new tab');
assert.ok(top.includes('btn-bookmark'), 'bookmark');
assert.ok(top.includes('btn-find'), 'find/search');
assert.ok(top.includes('btn-menu'), 'hamburger');
assert.ok(!top.includes('btn-vpn'), 'vpn not on top bar');
assert.ok(!top.includes('btn-private-tab'), 'private not on top bar');
assert.ok(!top.includes('btn-novnc'), 'novnc not on top bar');
assert.ok(html.includes('id="btn-vpn"'), 'vpn still in DOM (menu)');
assert.ok(html.includes('id="btn-private-tab"'), 'private still in DOM');
assert.ok(html.includes('id="btn-novnc"'), 'novnc still in DOM');
assert.ok(html.includes('menu-section'), 'menu sections');
assert.ok(css.includes('flex: 1 1 66%') || css.includes('chrome-top-wide-url') || css.includes('1 1 66%'), 'omnibox ~2/3');
console.log('[PASS] chrome-toolbar');
